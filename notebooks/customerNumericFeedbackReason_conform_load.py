# DBTITLE 1,Upsert operation on customernumericfeedbackreason_saz_tbl
try:
    spark.sql(f"""
    merge into {tgt_table} as dst
    using (select * from customernumericfeedbackreason_stg where reasonCode is not null) src
    on dst.custNumericFeedbackRatingID = src.custNumericFeedbackRatingID
    and dst.reasonCode = src.reasonCode
    and year(dst.effectiveToDate)=2999

    when matched and (
    nvl(dst.sourceSystemID,0) != nvl(src.sourceSystemID,0)
    ) then

    update set
    dst.sourceSystemID = src.sourceSystemID,
    dst.modifiedTimestamp = from_utc_timestamp(now(),'Europe/London')

    when not matched then
    insert (dst.custNumericFeedbackRatingID,
    dst.reasonCode,
    dst.createdTimestamp,
    dst.modifiedTimestamp,
    dst.effectiveFromDate,
    dst.effectiveToDate,
    dst.logicalDeletionTimestamp,
    dst.sourceSystemID)
    values (src.custNumericFeedbackRatingID,
    src.reasonCode,
    src.createdTimestamp,
    src.modifiedTimestamp,
    src.effectiveFromDate,
    src.effectiveToDate,
    src.logicalDeletionTimestamp,
    src.sourceSystemID)
    """).display()
except Exception as e:
    print("An error occurred: ",e)
    raise

