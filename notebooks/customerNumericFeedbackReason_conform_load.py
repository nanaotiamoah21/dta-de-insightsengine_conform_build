# DBTITLE 1,customernumericfeedbackreason_stg
spark.sql(f'''
select
custNumericFeedbackRatingID,
reasonCode,
from_utc_timestamp(now(),'Europe/London') createdTimestamp,
cast(null as timestamp) modifiedTimestamp,
from_utc_timestamp(now(),'Europe/London') effectiveFromDate,
cast('2999-12-31 00:00:00' as timestamp) effectiveToDate,
cast(null as timestamp) logicalDeletionTimestamp,
sourceSystemID
from
(select
u.custNumericFeedbackRatingID,
u.reasonCode,
cast({source_system_id} as int) sourceSystemID,
row_number() over (partition by u.custNumericFeedbackRatingID, u.reasonCode
                   order by u.responseTs desc) row1
from
-- unpivot paired rating / reason columns and explode the multi-select reasons
(select
md5(concat_ws('|', '{src_table_name}', nvl(a.SURVEY_ID,''), nvl(a.CODE_C_STORE_NUMBER,''), r.ratingName)) custNumericFeedbackRatingID,
r.ratingName,
replace(trim(replace(rs.reasonDescription, chr(160), ' ')), '’', "'") reasonCode,   -- reason text taken directly from source; non-breaking spaces and curly apostrophes normalised
to_timestamp(a.RESPONSE_DATE,'yyyy-MM-dd HH:mm:ss') responseTs
from {src_table} a
lateral view stack(4,
  'Colleague Service', a.COLLEAGUE_SERVICE, a.COLLEAGUE_SERVICE_IMPROVEMENT_2_0,
  'Clean and Tidy',    a.CLEAN_AND_TIDY,    a.CLEAN_AND_TIDY_SERVICE_IMPROVEMENT_2_0,
  'Time to Pay',       a.TIME_TO_PAY,       a.TIME_TO_PAY_SERVICE_IMPROVEMENT_2_0,
  'Were You Able To Get What You Wanted', cast(null as string), a.REASON_FOR_NOT_ABLE_TO_GET_WHAT_YOU_WANTED
) r as ratingName, ratingValue, reasonList
lateral view explode(split(r.reasonList, ',')) rs as reasonDescription
where r.ratingValue is not null
and nvl(trim(rs.reasonDescription),'') != ''
) u
) a1 where a1.row1=1
''').createOrReplaceTempView("customernumericfeedbackreason_stg")

display(spark.table('customernumericfeedbackreason_stg').limit(5))

